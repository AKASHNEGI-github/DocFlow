-- ---------------------------------------------------------------------
-- live_delete_requests / live_delete_request_approvers
-- Exactly 1 editor + 1 reviewer + 1 publisher; all three must APPROVE,
-- any single REJECTED cancels the whole request.
-- ---------------------------------------------------------------------
CREATE TABLE live_delete_requests (
  delete_request_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  document_id BIGINT NOT NULL,
  reason TEXT NOT NULL,
  status request_status NOT NULL DEFAULT 'PENDING',
  created_by BIGINT NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_by BIGINT NULL,
  updated_at TIMESTAMP NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_delete_requests_document FOREIGN KEY (document_id) REFERENCES documents(document_id),
  CONSTRAINT fk_delete_requests_created_by FOREIGN KEY (created_by) REFERENCES users(user_id),
  CONSTRAINT fk_delete_requests_updated_by FOREIGN KEY (updated_by) REFERENCES users(user_id),
  CONSTRAINT chk_delete_reason CHECK (length(trim(reason)) > 0)
);

CREATE INDEX idx_delete_requests_document ON live_delete_requests(document_id);
CREATE INDEX idx_delete_requests_status ON live_delete_requests(status);

CREATE TABLE live_delete_request_approvers (
  live_delete_request_approvers_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  delete_request_id BIGINT NOT NULL,
  approver_id BIGINT NOT NULL,
  approver_role delete_approver_role NOT NULL,
  approver_action approver_action NOT NULL DEFAULT 'PENDING',
  comments TEXT,
  created_by BIGINT NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_by BIGINT NULL,
  updated_at TIMESTAMP NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_delete_approvers_request FOREIGN KEY (delete_request_id) REFERENCES live_delete_requests(delete_request_id) ON DELETE CASCADE,
  CONSTRAINT fk_delete_approvers_user FOREIGN KEY (approver_id) REFERENCES users(user_id),
  CONSTRAINT fk_delete_approvers_created_by FOREIGN KEY (created_by) REFERENCES users(user_id),
  CONSTRAINT fk_delete_approvers_updated_by FOREIGN KEY (updated_by) REFERENCES users(user_id),
  CONSTRAINT uq_delete_request_role UNIQUE (delete_request_id, approver_role),
  CONSTRAINT uq_delete_request_user UNIQUE (delete_request_id, approver_id)
);

CREATE INDEX idx_delete_approvers_request ON live_delete_request_approvers(delete_request_id);
CREATE INDEX idx_delete_approvers_user ON live_delete_request_approvers(approver_id);
CREATE INDEX idx_delete_approvers_role ON live_delete_request_approvers(approver_role);

