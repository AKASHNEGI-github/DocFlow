-- ---------------------------------------------------------------------
-- Enums
-- ---------------------------------------------------------------------
CREATE TYPE user_login_status AS ENUM ('SUCCESS', 'FAILURE');

CREATE TYPE document_stage AS ENUM ('DRAFT', 'EDITORIAL', 'REVIEW', 'PUBLICATION', 'LIVE');

CREATE TYPE request_status AS ENUM ('NONE', 'PENDING', 'APPROVED', 'REJECTED', 'CANCELLED');

CREATE TYPE approver_action AS ENUM ('PENDING', 'APPROVED', 'REJECTED', 'CANCELLED');

CREATE TYPE delete_approver_role AS ENUM ('EDITOR', 'REVIEWER', 'PUBLISHER');

-- ---------------------------------------------------------------------
-- users
-- ---------------------------------------------------------------------
CREATE TABLE users (
  user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sso_id VARCHAR(100) UNIQUE,
  full_name VARCHAR(100) NOT NULL,
  email VARCHAR(150) UNIQUE NOT NULL,
  last_login TIMESTAMP NULL,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
  created_by BIGINT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_users_created_by FOREIGN KEY (created_by) REFERENCES users(user_id)
);

CREATE INDEX idx_users_email ON users(email);
CREATE INDEX idx_users_active ON users(is_active);
CREATE INDEX idx_users_deleted ON users(is_deleted);

-- ---------------------------------------------------------------------
-- user_passwords (one row per user, overwritten in place on change)
-- ---------------------------------------------------------------------
CREATE TABLE user_passwords (
  user_password_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL UNIQUE,
  hash_password VARCHAR(255) NOT NULL,
  created_by BIGINT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_by BIGINT NULL,
  updated_at TIMESTAMP NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_user_password_user FOREIGN KEY (user_id) REFERENCES users(user_id) ON DELETE CASCADE,
  CONSTRAINT fk_user_password_creator FOREIGN KEY (created_by) REFERENCES users(user_id),
  CONSTRAINT fk_user_password_updater FOREIGN KEY (updated_by) REFERENCES users(user_id)
);

CREATE INDEX idx_user_password_user ON user_passwords(user_id);

-- ---------------------------------------------------------------------
-- roles
-- ---------------------------------------------------------------------
CREATE TABLE roles (
  role_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  role_name VARCHAR(100) NOT NULL UNIQUE,
  role_level INTEGER NULL,
  description TEXT,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
  created_by BIGINT NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_by BIGINT NULL,
  updated_at TIMESTAMP NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_roles_created_by FOREIGN KEY (created_by) REFERENCES users(user_id),
  CONSTRAINT fk_roles_updated_by FOREIGN KEY (updated_by) REFERENCES users(user_id)
);

-- ---------------------------------------------------------------------
-- user_roles (one active role per user)
-- ---------------------------------------------------------------------
CREATE TABLE user_roles (
  user_roles_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL UNIQUE,
  role_id BIGINT NOT NULL,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
  assigned_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  created_by BIGINT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_by BIGINT NULL,
  updated_at TIMESTAMP NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_user_roles_user FOREIGN KEY (user_id) REFERENCES users(user_id) ON DELETE CASCADE,
  CONSTRAINT fk_user_roles_role FOREIGN KEY (role_id) REFERENCES roles(role_id),
  CONSTRAINT fk_user_roles_created_by FOREIGN KEY (created_by) REFERENCES users(user_id),
  CONSTRAINT fk_user_roles_updated_by FOREIGN KEY (updated_by) REFERENCES users(user_id)
);

CREATE INDEX idx_user_roles_user ON user_roles(user_id);
CREATE INDEX idx_user_roles_role ON user_roles(role_id);

-- ---------------------------------------------------------------------
-- documents
-- document_name = "V{version_no} - {title}", enforced UNIQUE. See the
-- comment in database/knex/migrations/006_create_documents.js for why
-- a plain UNIQUE(title) can't coexist with clone-based versioning.
-- ---------------------------------------------------------------------
CREATE TABLE documents (
  document_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category VARCHAR(100) NOT NULL,
  document_name VARCHAR(280) NOT NULL,
  content TEXT NOT NULL,
  version_no INTEGER NOT NULL DEFAULT 1,
  stage document_stage NOT NULL DEFAULT 'DRAFT',
  parent_document_id BIGINT NULL,
  root_document_id BIGINT NULL,
  is_locked BOOLEAN NOT NULL DEFAULT FALSE,
  is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
  created_by BIGINT NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_by BIGINT NULL,
  updated_at TIMESTAMP NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_documents_document_name UNIQUE (document_name),
  CONSTRAINT fk_documents_created_by FOREIGN KEY (created_by) REFERENCES users(user_id),
  CONSTRAINT fk_documents_updated_by FOREIGN KEY (updated_by) REFERENCES users(user_id),
  CONSTRAINT fk_documents_parent FOREIGN KEY (parent_document_id) REFERENCES documents(document_id),
  CONSTRAINT fk_documents_root FOREIGN KEY (root_document_id) REFERENCES documents(document_id),
  CONSTRAINT chk_documents_version CHECK (version_no >= 1)
);

CREATE INDEX idx_documents_stage ON documents(stage);
CREATE INDEX idx_documents_created_by ON documents(created_by);
CREATE INDEX idx_documents_deleted ON documents(is_deleted);
CREATE INDEX idx_documents_root ON documents(root_document_id);
CREATE INDEX idx_documents_parent ON documents(parent_document_id);

-- ---------------------------------------------------------------------
-- document_stage_history (append-only audit trail)
-- ---------------------------------------------------------------------
CREATE TABLE document_stage_history (
  document_stage_history_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  document_id BIGINT NOT NULL,
  from_stage document_stage NOT NULL,
  to_stage document_stage NOT NULL,
  old_status request_status NULL,
  new_status request_status NOT NULL,
  action_by BIGINT NOT NULL,
  action_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_stage_history_document FOREIGN KEY (document_id) REFERENCES documents(document_id),
  CONSTRAINT fk_stage_history_action_by FOREIGN KEY (action_by) REFERENCES users(user_id)
);

CREATE INDEX idx_stage_history_document ON document_stage_history(document_id);
CREATE INDEX idx_stage_history_action_at ON document_stage_history(action_at);

-- ---------------------------------------------------------------------
-- document_live (one row per version ever published; is_current marks
-- which version of a family is the one currently visible)
-- ---------------------------------------------------------------------
CREATE TABLE document_live (
  document_live_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  document_id BIGINT NOT NULL,
  root_document_id BIGINT NOT NULL,
  category VARCHAR(100) NOT NULL,
  document_name VARCHAR(280) NOT NULL,
  content TEXT NOT NULL,
  version_no INTEGER NOT NULL DEFAULT 1,
  is_current BOOLEAN NOT NULL DEFAULT TRUE,
  published_by BIGINT NOT NULL,
  published_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
  CONSTRAINT uq_document_live_document UNIQUE (document_id),
  CONSTRAINT fk_document_live_document FOREIGN KEY (document_id) REFERENCES documents(document_id),
  CONSTRAINT fk_document_live_root FOREIGN KEY (root_document_id) REFERENCES documents(document_id),
  CONSTRAINT fk_document_live_published_by FOREIGN KEY (published_by) REFERENCES users(user_id)
);

CREATE INDEX idx_document_live_deleted ON document_live(is_deleted);
CREATE INDEX idx_document_live_root ON document_live(root_document_id);

-- Partial unique index: structurally impossible for two versions of the
-- same family to both be "current", even if the app forgets to flip the
-- old row - Postgres itself rejects the insert.
CREATE UNIQUE INDEX uq_document_live_one_current_per_family
  ON document_live (root_document_id)
  WHERE is_current = true;

